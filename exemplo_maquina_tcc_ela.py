# 3. ANÁLISE DE SOBREVIDA & PROJEÇÃO TEMPORAL (LIFELINES)
# ==============================================================================
class SurvivalAnalyzer:
    """Gera curvas temporais de risco de manifestação por idade"""
    def __init__(self):
        self.wf = WeibullFitter()

    def generate_age_onset_distribution(self, mc_results):
        gene_info = mc_results["gene_info"]
        is_carrier = mc_results["is_carrier"]

        alpha = gene_info["weibull_alpha"]
        beta = gene_info["weibull_beta"]

        n_samples = len(is_carrier)
        simulated_onset_ages = np.random.weibull(beta, size=n_samples) * alpha
        onset_ages_carriers = simulated_onset_ages[is_carrier == 1]

        self.wf.fit(onset_ages_carriers, event_observed=np.ones_like(onset_ages_carriers))
        median_onset = self.wf.median_survival_time_

        return {
            "fitted_model": self.wf,
            "median_onset": median_onset
        }

