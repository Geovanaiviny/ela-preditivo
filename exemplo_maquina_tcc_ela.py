# 2. NÚCLEO ESTOCÁSTICO: REDE BAYESIANA & MONTE CARLO
# ==============================================================================
class BayesianMonteCarloEngine:
    """Executa a transmissão mendeliana probabilística e simulação de Monte Carlo"""
    def __init__(self, n_simulations=10000):
        self.n_simulations = n_simulations

    def _mendelian_transmission(self, g_paterno, g_materno):
        p_paterno_alt = g_paterno / 2.0
        p_materno_alt = g_materno / 2.0

        alelo_paterno = np.random.binomial(1, p_paterno_alt, size=self.n_simulations)
        alelo_materno = np.random.binomial(1, p_materno_alt, size=self.n_simulations)

        return alelo_paterno + alelo_materno

    def run_simulation(self, processed_data):
        g_p = processed_data["father_dosage"]
        g_m = processed_data["mother_dosage"]
        gene_info = processed_data["variant_details"]

        dosage_offspring = self._mendelian_transmission(g_p, g_m)
        is_carrier = (dosage_offspring > 0).astype(int)
        carrier_rate = np.mean(is_carrier)

        pen_max = gene_info["penetrance_max"]
        phenotype_prob = is_carrier * pen_max
        phenotype_manifestation = np.random.binomial(1, phenotype_prob)
        global_risk = np.mean(phenotype_manifestation)

        return {
            "dosage_samples": dosage_offspring,
            "is_carrier": is_carrier,
            "carrier_rate": carrier_rate,
            "global_risk": global_risk,
            "gene_info": gene_info
        }

